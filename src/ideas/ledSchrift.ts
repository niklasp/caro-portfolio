export interface Raster {
  daten: Uint8Array // 1 = Diode an; Zeile 0 ist oben
  breite: number
  hoehe: number
}

export const LED_STILE = {
  'Punktschrift 5×7': 'dioden',
  Kursiv: 'kursiv',
  Gesperrt: 'gesperrt',
  'Breit (jede zweite Diode)': 'breit',
} as const
export type LedStil = (typeof LED_STILE)[keyof typeof LED_STILE]

// Alle Stile sind dieselbe 5×7-Punktschrift — nur anders gesetzt. So bleibt
// jeder Strich genau eine Diode breit.
export function ledRaster(text: string, stil: string, zeilen: number): Raster {
  const glyphen = [...`${text.toUpperCase()}  •  `].map((z) => G[z] ?? G[' '])
  const dehnung = stil === 'breit' ? 2 : 1 // Spalten auseinanderziehen
  const abstand = stil === 'gesperrt' ? 3 : stil === 'breit' ? 3 : 1
  const neigung = stil === 'kursiv' ? 3 : 0 // Versatz der obersten Zeile nach rechts
  const breite = glyphen.reduce((s, g) => s + (g[0].length - 1) * dehnung + 1 + abstand, 0)
  const daten = new Uint8Array(breite * zeilen)
  const oben = Math.max(0, Math.floor((zeilen - 7) / 2))
  let x = 0
  for (const g of glyphen) {
    for (let r = 0; r < 7 && oben + r < zeilen; r++) {
      const schub = Math.round(((6 - r) / 6) * neigung)
      for (let c = 0; c < g[r].length; c++)
        if (g[r][c] === '#') daten[(oben + r) * breite + ((x + c * dehnung + schub) % breite)] = 1
    }
    x += (g[0].length - 1) * dehnung + 1 + abstand
  }
  return { daten, breite, hoehe: zeilen }
}
